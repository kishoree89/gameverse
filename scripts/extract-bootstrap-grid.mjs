// Keeps only Bootstrap's grid rules (container/row/col/gutters) so its !important
// spacing & flex utilities never clash with Tailwind classes of the same name.
import fs from 'node:fs';
import postcss from 'postcss';

const src = fs.readFileSync('node_modules/bootstrap/dist/css/bootstrap-grid.css', 'utf8');
const keep = /^(:root|\.container|\.row|\.col|\.g-|\.gx-|\.gy-|\.offset-|\.row-cols)/;
const root = postcss.parse(src);
root.walkRules((rule) => {
  if (!rule.selectors.every((s) => keep.test(s.trim()))) rule.remove();
});
root.walkAtRules((at) => { if (at.nodes && at.nodes.length === 0) at.remove(); });
root.walkComments((c) => c.remove());
fs.writeFileSync('src/styles/bootstrap-grid.css', '/* Generated by scripts/extract-bootstrap-grid.mjs – grid only */\n' + root.toString());
